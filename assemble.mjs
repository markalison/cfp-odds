// Builds the site from src/ and data.json: writes index.html, about.html and data.js.
// Usage: node build.mjs [sims], then node assemble.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const CFP = require('./engine.js');
const rd = (f) => readFileSync(new URL(f, import.meta.url), 'utf8');
// OneDrive sometimes holds a file for a moment while it syncs, so a failed write is retried briefly.
const wr = (f, s) => {
  for (let tries = 1; ; tries++) {
    try { return writeFileSync(new URL(f, import.meta.url), s); }
    catch (e) {
      if (tries >= 8 || !['UNKNOWN', 'EBUSY', 'EPERM'].includes(e.code)) throw e;
      Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 250 * tries);
    }
  }
};
const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));

// ---------- data.js ----------
const data = JSON.parse(rd('./data.json'));
const D = data.D;
// Only the default model is embedded. The page simulates the others when they're chosen.
const results = { blend: data.results.blend };
const r4 = (x) => (x == null ? null : Math.round(x * 1e4) / 1e4);
for (const res of Object.values(results)) {
  delete res.schedule;
  res.rating = res.rating.map((x) => Math.round(x * 100) / 100);
  res.teams.forEach((t) => { for (const k of ['cfp', 'bye', 'host', 'aq', 'champ', 'ccg', 'title', 'pNext', 'ifNext', 'ifLose']) t[k] = r4(t[k]); if (t.seed != null) t.seed = Math.round(t.seed * 100) / 100; });
}
const dataJs = '// Generated by assemble.mjs. Teams, games, ratings and the default simulation.\nwindow.CFP_DATA = ' + JSON.stringify({ D, results }) + ';\n';
wr('./data.js', dataJs);

// ---------- nfl-data.js ----------
const NFLD = JSON.parse(rd('./nfl-data.json'));
// Every ratings model's odds are embedded, so switching models is instant.
const nflResults = Object.fromEntries(Object.entries(NFLD.results).map(([k, r]) => [k, { teams: r.teams, homeWin: r.homeWin, model: r.model }]));
const nflJs = '// Generated by assemble.mjs. NFL teams, games, ratings models and simulated odds.\nwindow.NFL_DATA = ' + JSON.stringify({ D: NFLD.D, models: NFLD.models, ratings: NFLD.ratings, results: nflResults }) + ';\n';
wr('./nfl-data.js', nflJs);

// A version stamp on file links makes browsers fetch new files after each publish.
const V = createHash('sha1').update([dataJs, nflJs, rd('./engine.js'), rd('./js/app.js'), rd('./js/nfl.js'), rd('./nfl-engine.js'), rd('./js/theme.js'), rd('./css/styles.css')].join('')).digest('hex').slice(0, 10);

// ---------- Shared head and footer ----------
const HEAD = `  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Barlow+Condensed:wght@500;600;700&family=Barlow:wght@400;500;600&display=swap">
  <link rel="stylesheet" href="css/styles.css?v=${V}">
  <script src="js/theme.js?v=${V}"></script>`;
// Header: the sport menu (league logo and name) at the left, that sport's tabs, and the night-mode switch
// on its own at the right. Each page marks its current tab from the address's #; js/theme.js runs the
// menu and the switch.
const SPORTS = { ncaaf: { name: 'NCAAF', logo: 'https://upload.wikimedia.org/wikipedia/commons/d/dd/NCAA_logo.svg', href: './#rankings' }, nfl: { name: 'NFL', logo: 'https://upload.wikimedia.org/wikipedia/en/a/a2/National_Football_League_logo.svg', href: 'nfl.html#rankings' } };
const header = (page) => {
  const nfl = page === 'nfl', base = nfl ? 'nfl.html' : './', cur = SPORTS[nfl ? 'nfl' : 'ncaaf'];
  const option = (k) => `<a href="${SPORTS[k].href}"${SPORTS[k] === cur ? ' aria-current="true"' : ''}><img class="menu-logo" src="${SPORTS[k].logo}" alt=""><span>${SPORTS[k].name}</span></a>`;
  return `<header class="site-header">
  <div class="container header-bar">
    <div class="menu">
      <button class="btn menu-btn" id="menu-btn" type="button" aria-expanded="false" aria-controls="menu-panel" aria-label="Sport: ${cur.name}. Choose a sport"><img class="menu-sport" src="${cur.logo}" alt=""><span class="menu-name">${cur.name}</span><svg class="menu-caret" viewBox="0 0 24 24" aria-hidden="true"><path d="M7 10l5 5 5-5"></path></svg></button>
      <div class="menu-panel" id="menu-panel" hidden>
        ${option('nfl')}
        ${option('ncaaf')}
      </div>
    </div>
    <nav class="tabs" aria-label="${nfl ? 'NFL' : 'College football'} views">
      <a href="${base}#rankings" data-page="rankings">${nfl ? 'Standings' : 'Rankings'}</a>
      <a href="${base}#playoff" data-page="playoff">Bracket</a>
      <a href="${base}#scores" data-page="scoreboard">Scores</a>
    </nav>
    <button class="theme-switch" id="theme" type="button" role="switch" aria-checked="false" aria-label="Night mode" title="Night mode"></button>
  </div>
</header>`;
};
const footer = (page) => `<footer class="site-footer">
  <div class="footer-inner">
    <div class="footer-brand">
      <p>Playoff odds for the ${D.season} season, from simulating every remaining game and committee ranking.</p>
    </div>
    <nav aria-label="Footer">
      <a class="footer-link" href="about.html"${page === 'about' ? ' aria-current="page"' : ''}>About</a>
    </nav>
${page === 'odds' ? '    <div class="status footer-status" id="status" aria-live="polite"></div>\n' : ''}    <p class="footer-fine">Data from ESPN and the ratings sources listed on the About page. Not affiliated with the College Football Playoff.</p>
  </div>
</footer>`;

// ---------- About page text ----------
const M = CFP.M;
const METHOD = [
  `Each game is decided by the rating gap plus home field, with ${M.gameSD} points of game randomness. Each team’s true strength also varies by ${M.teamSD} points per simulated season, so hot streaks carry through.`,
  'Conference standings produce two title-game teams each simulation, or one per division in the Sun Belt.',
  `A simulated committee scores every team: rating × ${M.wRating}, −${M.wLoss} per loss with −${M.wLoss3} more past two losses, schedule strength, +${M.wTop10} per top-10 win, +${M.wTop25} per 11-25 win, −${M.wBadLoss} for a loss outside the top 60, +${M.wChampP4} for a power-conference title.`,
  `Part of the current CFP ranking carries forward (${Math.round(M.wAnchor * 100)}% of the gap between it and the model), and committee opinion varies by ${M.committeeSD} points per simulation. A head-to-head winner jumps a team within ${M.h2hWindow} points.`,
  'The projected field follows the bid rules: the likeliest champion of each power conference, the likeliest Group of 6 bid, then the seven best remaining odds. The Playoff page seeds it by average seed. With Simulate games on, each game’s win chance comes from the two ratings, with home field for the higher seed in the first round, and the favorite advances. Title odds come from the full simulation, so a team can lead them without being favored in this one bracket.',
  '40,000 seasons are simulated each time, which puts a team near 50% within about half a point.',
  'Picking a winner locks that game in every simulation, so its opponent loses it. All odds then update, including those of teams that weren’t playing in it.'
].map((s) => `        <li>${s}</li>`).join('\n');

const day = (d) => new Date(d + 'T12:00:00Z').toLocaleDateString('en-US', { month: 'short', day: 'numeric', timeZone: 'UTC' });
const groups = ['Point-based', 'Recent form', 'Results only'];
const SOURCES = groups.map((g) => {
  const items = D.sources.models.filter((m) => m.group === g).map((m) => {
    const when = m.k === 'fpi' ? 'updated each time the Odds page loads' : 'through ' + day(D.sources.thru[m.k]);
    return `        <li><a href="${esc(m.url)}" target="_blank" rel="noopener">${esc(m.label)}</a>, ${when}</li>`;
  }).join('\n');
  return `      <h3>${g}</h3>\n      <ul>\n${items}\n      </ul>`;
}).join('\n') + `\n      <p><b>All models average</b> uses one rating from each of these: ${D.sources.consensus.map((k) => esc((D.sources.models.find((m) => m.k === k) || { label: k }).label)).join(', ')}.</p>`;
const UPDATED = new Date(D.asOf).toLocaleDateString('en-US', { month: 'long', day: 'numeric', year: 'numeric', timeZone: 'America/New_York' });

// ---------- Pages ----------
const fill = (tpl, page, extra = {}) => {
  let html = rd(tpl).replace('{{HEAD}}', () => HEAD).replace('{{HEADER}}', () => header(page)).replace('{{FOOTER}}', () => footer(page)).replace(/\{\{V\}\}/g, V);
  for (const [k, v] of Object.entries(extra)) html = html.replace(`{{${k}}}`, () => v);
  const left = html.match(/\{\{\w+\}\}/);
  if (left) throw new Error(`${tpl}: ${left[0]} was not filled`);
  return html;
};
wr('./index.html', fill('./src/index.html', 'odds'));
wr('./about.html', fill('./src/about.html', 'about', { METHOD, SOURCES, UPDATED }));
const NM = NFLD.results.all.model;
const NFL_METHOD = [
  `Every remaining regular-season game is played out ${NFLD.sims.toLocaleString('en-US')} times. Each game is decided by the rating gap plus ${NM.hfa} points for the home team, with ${NM.gameSD} points of game randomness, and each team’s strength also drifts by ${NM.teamSD} points per simulated season.`,
  `Ratings are grouped by how they calculate. Point-based: ESPN’s FPI, Sagarin, TeamRankings and this site’s points rating (this season’s scores, margins capped at ${NM.capMargin}, adjusted for opponent and home field). Elo: <a href="https://github.com/greerreNFL/nfelo" target="_blank" rel="noopener">nfelo</a> and a classic Elo run over every game since 1999 (25 Elo points to a point). Betting market: ratings fitted to this season’s point spreads from <a href="https://github.com/nflverse/nfldata" target="_blank" rel="noopener">nflverse</a>, recent weeks counting most. Recent form: TeamRankings’ last five games and Sagarin’s recent rating. The default averages one rating from each source: ${NFLD.avg.join(', ')}.`,
  'Division titles and wild cards follow the NFL’s tiebreakers: head-to-head, division record, common games, conference record, strength of victory and strength of schedule, then a coin toss.',
  'Seven teams per conference make the playoffs. The four division winners are seeded 1-4 and the three wild cards 5-7. Only the 1 seed gets a bye, and the top remaining seed hosts each game. The Super Bowl is on a neutral field.',
  'Playoffs after a win or loss show the chance to make the playoffs if the team wins or loses its next game.'
].map((s) => `      <li>${s}</li>`).join('\n');
wr('./nfl.html', fill('./src/nfl.html', 'nfl', { NFL_METHOD }));
console.log(`index.html, about.html, nfl.html, data.js ${(dataJs.length / 1024).toFixed(0)} KB, version ${V}`);
