// Builds the site from src/ and data.json: writes index.html, about.html and data.js.
// Usage: node build.mjs [sims], then node assemble.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const CFP = require('./engine.js');
const rd = (f) => readFileSync(new URL(f, import.meta.url), 'utf8');
// OneDrive sometimes holds a file for a moment while it syncs, so a failed write is retried briefly.
const wr = (f, s) => {
  for (let tries = 1; ; tries++) {
    try { return writeFileSync(new URL(f, import.meta.url), s); }
    catch (e) {
      if (tries >= 8 || !['UNKNOWN', 'EBUSY', 'EPERM'].includes(e.code)) throw e;
      Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 250 * tries);
    }
  }
};
const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));

// The data files are built from local JSON (gitignored), which can be older than the committed data the
// refresh bot pushed (pulled in by git). Never replace newer data with older: keep the committed file then.
function writeData(file, js, asOf) {
  let old = null;
  try { old = rd(file); } catch (e) {}
  const m = old && old.match(/"asOf":"([^"]+)"/);
  if (m && asOf && m[1] > asOf) {
    console.warn(file + ': kept the committed data from ' + m[1] + '; the local build (' + asOf + ') is older. Run its build script to refresh it.');
    return old;
  }
  wr(file, js);
  return js;
}

// ---------- data.js ----------
const data = JSON.parse(rd('./data.json'));
const D = data.D;
// Only the default model is embedded. The page simulates the others when they're chosen.
const results = { blend: data.results.blend };
const r4 = (x) => (x == null ? null : Math.round(x * 1e4) / 1e4);
for (const res of Object.values(results)) {
  delete res.schedule;
  res.rating = res.rating.map((x) => Math.round(x * 100) / 100);
  res.teams.forEach((t) => { for (const k of ['cfp', 'bye', 'host', 'aq', 'champ', 'ccg', 'title', 'pNext', 'ifNext', 'ifLose']) t[k] = r4(t[k]); if (t.seed != null) t.seed = Math.round(t.seed * 100) / 100; });
}
let dataJs = '// Generated by assemble.mjs. Teams, games, ratings and the default simulation.\nwindow.CFP_DATA = ' + JSON.stringify({ D, results }) + ';\n';
dataJs = writeData('./data.js', dataJs, D.asOf);

// ---------- nfl-data.js ----------
const NFLD = JSON.parse(rd('./nfl-data.json'));
// Every ratings model's odds are embedded, so switching models is instant.
const nflResults = Object.fromEntries(Object.entries(NFLD.results).map(([k, r]) => [k, { teams: r.teams, homeWin: r.homeWin, model: r.model }]));
let nflJs = '// Generated by assemble.mjs. NFL teams, games, ratings models and simulated odds.\nwindow.NFL_DATA = ' + JSON.stringify({ D: NFLD.D, models: NFLD.models, ratings: NFLD.ratings, results: nflResults }) + ';\n';
nflJs = writeData('./nfl-data.js', nflJs, NFLD.D.asOf);

// ---------- nba-data.js ----------
const NBAD = JSON.parse(rd('./nba-data.json'));
// Home win chances go in as one compact list per model, in schedule order (js/nba.js turns them back into a lookup).
const nbaResults = Object.fromEntries(Object.entries(NBAD.results).map(([k, r]) => [k, { teams: r.teams, hw: NBAD.D.games.map((g) => (r.homeWin[g.id] == null ? null : Math.round(r.homeWin[g.id] * 1000) / 1000)), model: r.model }]));
let nbaJs = '// Generated by assemble.mjs. NBA teams, games, ratings models and simulated odds.\nwindow.NBA_DATA = ' + JSON.stringify({ D: NBAD.D, models: NBAD.models, ratings: NBAD.ratings, results: nbaResults }) + ';\n';
nbaJs = writeData('./nba-data.js', nbaJs, NBAD.D.asOf);

// A version stamp on file links makes browsers fetch new files after each publish.
const V = createHash('sha1').update([dataJs, nflJs, nbaJs, rd('./engine.js'), rd('./js/app.js'), rd('./js/nfl.js'), rd('./nfl-engine.js'), rd('./js/nba.js'), rd('./nba-engine.js'), rd('./js/theme.js'), rd('./css/styles.css')].join('')).digest('hex').slice(0, 10);

